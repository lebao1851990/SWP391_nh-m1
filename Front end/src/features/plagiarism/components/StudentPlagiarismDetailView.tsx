'use client';

import React from 'react';
import { useStudentPlagiarismDetail } from '../hooks';
import { AxiosError } from 'axios';
import { AppLink as Link } from '@/components/ui/app-link';

export function StudentPlagiarismDetailView({ recordId }: { recordId: string }) {
  const { data, isLoading, isError, error } = useStudentPlagiarismDetail(recordId);

  if (isLoading) {
    return (
      <div className="flex h-64 items-center justify-center">
        <div className="text-on-surface-variant font-label-md">Loading plagiarism report...</div>
      </div>
    );
  }

  if (isError) {
    const status = (error as AxiosError)?.response?.status;
    if (status === 404 || status === 403) {
      return (
        <div className="flex flex-col h-64 items-center justify-center p-space-lg text-center gap-space-sm">
          <span className="material-symbols-outlined text-outline text-[48px]">search_off</span>
          <h2 className="font-headline-md text-headline-md text-on-surface">Report Not Found</h2>
          <p className="font-body-md text-on-surface-variant">The requested report does not exist or you do not have permission.</p>
        </div>
      );
    }
    return (
      <div className="flex flex-col h-64 items-center justify-center p-space-lg text-center gap-space-sm">
        <span className="material-symbols-outlined text-error text-[48px]">error</span>
        <h2 className="font-headline-md text-headline-md text-on-surface">Error</h2>
        <p className="font-body-md text-on-surface-variant">{(error as Error).message}</p>
      </div>
    );
  }

  if (!data) return null;

  return (
    <>
      <div className="flex-1 flex flex-col min-h-0 overflow-y-auto bg-surface">
        <div className="max-w-7xl mx-auto px-space-lg py-space-lg w-full">
          <div className="flex flex-col w-full">
            <div className="flex flex-wrap items-center justify-between gap-space-sm mb-space-md">
              <div className="flex flex-col">
                <div className="flex items-center gap-1.5 font-label-sm text-label-sm text-outline mb-1">
                  <Link className="hover:text-on-surface cursor-pointer" href="/student/submissions">Submissions</Link>
                  <span className="material-symbols-outlined text-[14px]">chevron_right</span>
                  <span className="text-on-surface font-semibold">Integrity Report #{data.recordId.substring(0,8)}</span>
                </div>
                <div className="flex items-center gap-3">
                  <h1 className="font-headline-lg text-headline-lg text-on-surface tracking-tight">Integrity Report</h1>
                  <span className={`px-2 py-0.5 rounded font-label-sm text-label-sm font-semibold flex items-center gap-1 shadow-sm ${data.isFlagged ? 'bg-error-container text-on-error-container' : 'bg-surface-container text-on-surface-variant'}`}>
                    <span className="material-symbols-outlined text-[14px]">{data.isFlagged ? 'warning' : 'info'}</span>
                    {data.isFlagged ? 'High Similarity Flagged' : 'Standard Check Passed'}
                  </span>
                </div>
                <p className="font-body-sm text-body-sm text-on-surface-variant mt-0.5">
                  Exam: <span className="font-semibold text-on-surface">{data.examName}</span>
                </p>
              </div>
            </div>

            <div className="bg-surface-container-lowest rounded-xl p-space-md shadow-sm border border-outline-variant/30 flex flex-col">
              <div className="flex items-center justify-between font-label-sm text-label-sm pb-2 border-b border-outline-variant/30 mb-2">
                <span className="text-outline">Calculated Similarity:</span>
                <span className={`font-bold ${data.isFlagged ? 'text-error' : 'text-on-surface'}`}>{data.similarityRate}%</span>
              </div>
              <div className="flex items-center justify-between font-label-sm text-label-sm">
                <span className="text-outline">Evidence:</span>
                <span className="font-medium text-on-surface">{data.evidence ? data.evidence.length : 0} structural matches recorded.</span>
              </div>
            </div>
            
            <div className="mt-space-md pt-space-xs flex items-center gap-1.5 font-label-sm text-[11px] text-outline leading-tight">
              <span className="material-symbols-outlined text-[14px] shrink-0">shield</span>
              <span>This report is generated by the CodeAssess AST Evaluation Engine. Details are logged securely.</span>
            </div>
          </div>
        </div>
      </div>
    </>
  );
}
